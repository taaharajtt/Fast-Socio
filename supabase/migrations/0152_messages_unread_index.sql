-- =============================================================================
-- FAST SOCIO — Index the unread-message probe (perf audit F6, Phase 1)
--
-- WHY
-- The dock's chat badge counts unread DMs like this (src/app/(student)/layout.tsx
-- and again in src/components/chat/dock-realtime.tsx):
--
--   select count(*) from messages where sender_id <> $me and read_at is null
--
-- Note what is NOT in that predicate: anything scoping the query to the caller.
-- Scoping is left entirely to the RLS policy "participants read conversation
-- messages" (migration 0032), which is an EXISTS against `conversations`.
--
-- That is correct, and it is also the slowest possible shape. Across all 152
-- migrations there is exactly one index on `messages`:
--
--   messages_conversation_idx on public.messages (conversation_id, created_at)
--
-- Nothing indexes `read_at`. So the planner's best available route is to find
-- every row in the WHOLE TABLE with read_at is null and evaluate the policy's
-- sub-select for each one. The work scales with the app's total unread volume,
-- not with the asking user's — and this query runs in the student layout on
-- every hard page load, and again (debounced 350ms) on every realtime message
-- event for every connected client.
--
-- Today the table is small and this is invisible. It gets worse precisely as
-- the app succeeds, which is the wrong time to discover it.
--
-- WHAT THIS DOES
-- A partial index over unread rows only. `read_at is null` is highly selective
-- in the steady state (most messages get read), so the index stays a small
-- fraction of the table, and leading with `conversation_id` lets the planner
-- feed the RLS EXISTS directly instead of filtering afterwards.
--
-- `sender_id` is included so the `sender_id <> $me` half is answered from the
-- index without a heap fetch. It is deliberately NOT a leading column: `<>` is
-- not an equality predicate and cannot drive an index scan.
--
-- WHAT THIS DOES NOT DO
-- This makes the existing query cheap; it does not make it CORRECT in shape.
-- The real fix is to drive the count from `conversations` (where the user IS an
-- indexed column, via conversations_user_low_idx / _high_idx) rather than
-- scanning `messages` and letting a policy filter the result. That is Phase 3
-- of the audit and needs a matching change in two client call sites. This index
-- is the half that is safe to ship on its own, today, with no code change.
--
-- SAFETY
-- CREATE INDEX CONCURRENTLY takes no exclusive lock, so writes to `messages`
-- continue throughout. It CANNOT run inside a transaction block — Supabase's
-- migration runner wraps statements in one by default, so if this fails with
-- "CREATE INDEX CONCURRENTLY cannot run inside a transaction block", run the
-- statement by hand against production instead of wrapping it.
--
-- A failed CONCURRENTLY build leaves an INVALID index behind rather than
-- rolling back. Check for that before retrying:
--
--   select indexrelid::regclass, indisvalid
--     from pg_index where indrelid = 'public.messages'::regclass;
--
--   -- if messages_unread_idx shows indisvalid = false:
--   drop index concurrently if exists public.messages_unread_idx;
--
-- VERIFY (run as the authenticated role — as superuser RLS is bypassed and the
-- plan will look fine no matter what):
--
--   begin;
--   set local role authenticated;
--   set local request.jwt.claims = '{"sub":"<REAL-USER-UUID>","role":"authenticated"}';
--   explain (analyze, buffers)
--     select count(*) from messages
--      where sender_id <> auth.uid() and read_at is null;
--   rollback;
--
-- Expect the sequential scan on `messages` to disappear and `shared read`
-- buffers to drop. Compare against the same plan captured before this ran.
-- =============================================================================

create index concurrently if not exists messages_unread_idx
  on public.messages (conversation_id)
  include (sender_id)
  where read_at is null;
